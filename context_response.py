def generate_context_response(text, emotion):
    situation = analyze_situation(text)

    messages = CONTEXT_RESPONSES.get(
        (emotion, situation),
        DEFAULT_RESPONSES.get(
            emotion,
            ["오늘의 이야기를 들려줘서 고마워요."]
        )
    )

    response = random.choice(messages)

    return {
        "emotion": emotion,
        "situation": situation,
        "response": response,
    }


