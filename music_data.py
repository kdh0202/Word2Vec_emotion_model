MOOD_CHANGE = {
    "행복": "행복",
    "슬픔": "평온",
    "분노": "행복",
    "피로": "평온",
    "평온": "행복",
}


def recommend_songs(emotion, purpose, count=3, genre="전체"):
    if emotion not in SONGS:
        return []

    target_emotion = emotion

    if purpose == "기분 전환":
        target_emotion = MOOD_CHANGE.get(emotion, emotion)

    genre_data = SONGS.get(target_emotion, {})

    # 전체 장르 또는 특정 장르 선택
    if genre == "전체":
        songs = [
            song
            for genre_songs in genre_data.values()
            for song in genre_songs
        ]
    else:
        songs = genre_data.get(genre, [])

    # 제목과 가수를 기준으로 중복 제거
    unique_songs = list({
        (title, artist): (title, artist, reason)
        for title, artist, reason in songs
    }.values())

    if not unique_songs:
        return []

    count = max(1, min(int(count), len(unique_songs)))

    return random.sample(unique_songs, count)


if __name__ == "__main__":
    for emotion in SONGS:
        for genre in SONGS[emotion]:
            songs = recommend_songs(
                emotion,
                "현재 감정에 어울리는 노래",
                count=3,
                genre=genre,
            )
            print(f"\n[{emotion}] [{genre}]")
            for title, artist, reason in songs:
                print(f"- {title} / {artist}: {reason}")
